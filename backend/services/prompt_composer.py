"""
Prompt Composer Service — assembles the layered prompt system.
Final prompt = compiler + family + template spec + category pack + concept slots + product data.
"""

import json
from pathlib import Path
from models.schemas import OptionCandidate, OptionSummary, ProductResponse, TemplateResponse
import structlog

log = structlog.get_logger()

DATA_DIR = Path(__file__).parent.parent / "data"


class PromptComposerService:
    """
    Assembles all prompt layers per section 8 of the PRD.
    Versions are tracked — each AI run records the component versions used.
    """

    def __init__(self):
        self._components = self._load_components()

    def _load_components(self) -> dict:
        path = DATA_DIR / "prompt_components.json"
        if path.exists():
            return json.loads(path.read_text())
        return {}

    def get_compiler(self) -> tuple[str, str]:
        """Returns (content, version) for the compiler layer."""
        comp = self._components.get("compiler", {})
        return comp.get("content", self._default_compiler()), comp.get("version", "1.0")

    def get_family_prompt(self, family: str) -> tuple[str, str]:
        """Returns (content, version) for the family prompt."""
        families = self._components.get("families", {})
        family_data = families.get(family, {})
        return family_data.get("content", f"[Family: {family}]"), family_data.get("version", "1.0")

    def get_category_pack(self, category: str) -> tuple[str, str]:
        """Returns (content, version) for the category pack."""
        packs = self._components.get("category_packs", {})
        pack_data = packs.get(category, packs.get("default", {}))
        return pack_data.get("content", f"[Category: {category}]"), pack_data.get("version", "1.0")

    def _default_compiler(self) -> str:
        return """PRODUCT FIDELITY RULES (non-negotiable):
- Use the attached reference product image EXACTLY as shown
- Do NOT redraw, recolor, or alter the product appearance in any way
- The product must remain photorealistic and true to the reference

FINANCIAL ACCURACY:
- Show only the price and offer that match the live product page
- Never display cost price or internal margin data
- Discount percentage must match actual MRP vs SP calculation

TEXT AND LAYOUT:
- Keep text within safe zones (10% margin on all edges)
- Ensure text is legible at mobile resolution (minimum 16px equivalent)
- Honour the aspect ratio of the template exactly
- All text slots follow the character limits specified in the template

BANNED ELEMENTS:
- No competitor logos or branding
- No medical or health claims unless in category approved list
- No explicit before/after transformation imagery
- No price manipulation or inflated crossed-out prices"""

    def compose_prompt(
        self,
        candidate: OptionCandidate,
        summary: OptionSummary,
        product: ProductResponse,
        template: TemplateResponse,
    ) -> tuple[str, dict[str, str]]:
        """
        Compose the full layered prompt.
        Returns (prompt_text, versions_used_dict).
        """
        compiler, compiler_v = self.get_compiler()
        family_prompt, family_v = self.get_family_prompt(template.family)
        category_pack, category_v = self.get_category_pack(product.category)

        versions = {
            "compiler": compiler_v,
            f"family_{template.family}": family_v,
            f"category_{product.category}": category_v,
        }

        prompt = f"""{compiler}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
TEMPLATE: {template.name} ({template.family})
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
{family_prompt}

Layout: {template.spec.layout}
Visual world: {template.spec.visual_world}
Human presence: {template.spec.human_presence}

Aspect ratio: {', '.join(template.spec.aspect_ratios)}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
CATEGORY PACK: {product.category}
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
{category_pack}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
CONCEPT BRIEF
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Hook (first 3 seconds): "{summary.hook_line}"
Problem: {candidate.problem}
Angle: {candidate.angle}
Offer: {candidate.offer}
Claims in use: {', '.join(summary.claims_used) or 'None'}

How it looks in this template:
{summary.how_it_looks}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
PRODUCT DATA
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Title: {product.title}
Selling price: ₹{product.sp}
MRP: ₹{product.mrp}
Discount: {product.discount_percent:.0f}% off
Category: {product.category}
Description: {product.description}

TEXT OVERLAYS (apply as separate layers — not generated by the image model):
{self._format_text_slots(template, summary)}

Reference image: [ATTACHED — use as product anchor, do not alter]"""

        return prompt, versions

    def _format_text_slots(self, template: TemplateResponse, summary: OptionSummary) -> str:
        lines = []
        for slot in template.spec.text_slots:
            if slot.model_generated:
                lines.append(f"- {slot.zone.upper()} ({slot.id}, max {slot.max_chars} chars): [AI to suggest in template context]")
            else:
                lines.append(f"- {slot.zone.upper()} ({slot.id}, max {slot.max_chars} chars): [User/system to set]")
        return "\n".join(lines) if lines else "No text slots defined."
